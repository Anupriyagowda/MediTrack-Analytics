-- check the columns of the dataset table
describe meditrack_dataset;

-- view the first 10 records
select *
from meditrack_dataset
limit 10;

-- query 1: total revenue generated from all prescriptions
select sum(totalamount) as total_revenue
from meditrack_dataset;

-- query 2: average prescription amount
select avg(totalamount) as average_prescription_amount
from meditrack_dataset;

-- query 3: total quantity of medicines prescribed
select sum(quantity) as total_quantity
from meditrack_dataset;

-- query 4: prescription with the highest total amount
select prescriptionid,
       patientname,
       medicationname,
       totalamount
from meditrack_dataset
where totalamount = (
    select max(totalamount)
    from meditrack_dataset
);

-- query 5: prescription with the lowest total amount
select prescriptionid,
       patientname,
       medicationname,
       totalamount
from meditrack_dataset
where totalamount = (
    select min(totalamount)
    from meditrack_dataset
);

-- query 6: total revenue generated by each medication
select medicationname,
       sum(totalamount) as total_revenue
from meditrack_dataset
group by medicationname
order by total_revenue desc;

-- query 7: doctor-wise prescription count and revenue
select doctorname,
       count(prescriptionid) as prescription_count,
       sum(totalamount) as total_revenue,
       avg(totalamount) as average_revenue
from meditrack_dataset
group by doctorname
order by total_revenue desc;

-- query 8: payment status-wise prescription and revenue analysis
select paymentstatus,
       count(*) as prescription_count,
       sum(totalamount) as total_amount,
       avg(totalamount) as average_amount
from meditrack_dataset
group by paymentstatus
order by total_amount desc;

-- query 9: calculate prescription amount using quantity and unit price
select prescriptionid,
       medicationname,
       quantity,
       unitprice,
       quantity * unitprice as calculated_amount
from meditrack_dataset;

-- query 10: compare calculated amount with stored total amount
select prescriptionid,
       medicationname,
       quantity,
       unitprice,
       totalamount,
       quantity * unitprice as calculated_amount,
       totalamount - (quantity * unitprice) as difference
from meditrack_dataset
where totalamount <> (quantity * unitprice);

-- query 11: medications generating more than 100000 revenue
select medicationname,
       sum(totalamount) as total_revenue
from meditrack_dataset
group by medicationname
having sum(totalamount) > 100000
order by total_revenue desc;

-- query 12: create patients table
create table patients as
select distinct
    patientid,
    patientname,
    dob,
    phone
from meditrack_dataset;

-- query 13: create doctors table
create table doctors as
select distinct
    doctorname
from meditrack_dataset;

-- query 14: create medications table
create table medications as
select distinct
    medicationname,
    dosage,
    unitprice
from meditrack_dataset;

-- JOINs --

-- query 15: display patient details with prescription details
-- inner join --
select
    p.patientid,
    p.patientname,
    p.phone,
    m.medicationname,
    m.quantity,
    m.totalamount
from patients p
inner join meditrack_dataset m
    on p.patientid = m.patientid;
    
-- query 16: find total amount spent by each patient
select
    p.patientid,
    p.patientname,
    sum(m.totalamount) as total_spent
from patients p
inner join meditrack_dataset m
    on p.patientid = m.patientid
group by p.patientid, p.patientname
order by total_spent desc;

-- query 17: calculate medicine cost for each patient
select
    p.patientname,
    m.medicationname,
    m.quantity,
    m.unitprice,
    m.quantity * m.unitprice as calculated_cost
from patients p
inner join meditrack_dataset m
    on p.patientid = m.patientid
order by calculated_cost desc;

-- query 18: display all patients with their prescriptions
-- left join --
select
    p.patientid,
    p.patientname,
    m.prescriptionid,
    m.medicationname,
    m.totalamount
from patients p
left join meditrack_dataset m
    on p.patientid = m.patientid;
    
-- query 19: doctor-wise prescription details using join
select
    d.doctorname,
    m.prescriptionid,
    m.patientname,
    m.medicationname,
    m.totalamount
from doctors d
inner join meditrack_dataset m
    on d.doctorname = m.doctorname
order by m.totalamount desc;
    
-- query 20: doctor-wise total revenue using join and aggregation
select
    d.doctorname,
    count(m.prescriptionid) as prescription_count,
    sum(m.totalamount) as total_revenue
from doctors d
inner join meditrack_dataset m
    on d.doctorname = m.doctorname
group by d.doctorname
order by total_revenue desc;

-- query 21: medication-wise quantity and revenue using join

select
    md.medicationname,
    sum(m.quantity) as total_quantity,
    sum(m.totalamount) as total_revenue
from medications md
inner join meditrack_dataset m
    on md.medicationname = m.medicationname
    and md.dosage = m.dosage
    and md.unitprice = m.unitprice
group by md.medicationname
order by total_revenue desc;

-- query 22: find patients whose total spending is above the average patient spending

select
    p.patientid,
    p.patientname,
    sum(m.totalamount) as total_spent
from patients p
inner join meditrack_dataset m
    on p.patientid = m.patientid
group by p.patientid, p.patientname
having sum(m.totalamount) > (
    select avg(patient_total)
    from (
        select sum(totalamount) as patient_total
        from meditrack_dataset
        group by patientid
    ) as patient_totals
)
order by total_spent desc;

-- query 23: find doctors generating more than the average doctor revenue

select
    d.doctorname,
    sum(m.totalamount) as total_revenue
from doctors d
inner join meditrack_dataset m
    on d.doctorname = m.doctorname
group by d.doctorname
having sum(m.totalamount) > (
    select avg(doctor_total)
    from (
        select sum(totalamount) as doctor_total
        from meditrack_dataset
        group by doctorname
    ) as doctor_totals
)
order by total_revenue desc;

-- query 24: calculate remaining stock value for each medication

select
    md.medicationname,
    m.stockquantity,
    m.unitprice,
    m.stockquantity * m.unitprice as stock_value
from medications md
inner join meditrack_dataset m
    on md.medicationname = m.medicationname
    and md.dosage = m.dosage
    and md.unitprice = m.unitprice
order by stock_value desc;

-- query 25: find payment status with total quantity and revenue

select
    paymentstatus,
    count(*) as prescription_count,
    sum(quantity) as total_quantity,
    sum(totalamount) as total_revenue,
    avg(totalamount) as average_amount,
    max(totalamount) as highest_amount,
    min(totalamount) as lowest_amount
from meditrack_dataset
group by paymentstatus
order by total_revenue desc;

